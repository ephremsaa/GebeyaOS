import { describe, it, expect, beforeAll, afterAll } from 'vitest';
import { NotFoundException, BadRequestException, ForbiddenException } from '@nestjs/common';
import * as jwt from 'jsonwebtoken';
import { DatabaseService } from '../../src/common/database/database.service';
import { TenantContextService } from '../../src/common/tenant/tenant-context.service';
import { OnboardingService } from '../../src/modules/onboarding/onboarding.service';
import { BranchActivationService } from '../../src/modules/branch-activation/branch-activation.service';
import { PlatformAdminService } from '../../src/modules/platform-admin/platform-admin.service';
import { JWT_SECRET } from '../../src/common/guards/jwt-auth.guard';

describe('Tenant Onboarding, Branch Activation & Branding (Step 4)', () => {
  let db: DatabaseService;
  let tenantContextService: TenantContextService;
  let onboardingService: OnboardingService;
  let activationService: BranchActivationService;
  let platformService: PlatformAdminService;

  beforeAll(async () => {
    process.env.DB_NAME = 'gebeyaos_test';
    tenantContextService = new TenantContextService();
    db = new DatabaseService(tenantContextService);
    db.onModuleInit();

    onboardingService = new OnboardingService(db);
    activationService = new BranchActivationService(db);
    platformService = new PlatformAdminService(db);
  });

  afterAll(async () => {
    if (db) {
      await db.onModuleDestroy();
    }
  });

  describe('1. Owner Invitation Token Verification', () => {
    it('rejects invalid or non-existent token with NotFoundException', async () => {
      await expect(onboardingService.verifyInvite('inv_non_existent_token_12345')).rejects.toThrow(
        NotFoundException,
      );
    });

    it('verifies a valid tenant invite link generated by platform admin', async () => {
      const adminLogin = await platformService.login({
        username: 'platform_admin',
        password: 'PlatformAdmin2026!',
      });

      const uniqueSlug = `finfine-${Date.now()}`;
      const created = await platformService.createTenant(
        {
          name: 'Finfine Supermarket',
          slug: uniqueSlug,
          plan: 'growth',
          ownerName: 'Chala Gemechu',
          ownerEmailOrPhone: 'chala@finfine.et',
        },
        adminLogin.admin.id,
      );

      const invite = await onboardingService.verifyInvite(created.inviteToken);
      expect(invite.valid).toBe(true);
      expect(invite.tenantName).toBe('Finfine Supermarket');
      expect(invite.tenantSlug).toBe(uniqueSlug);
      expect(invite.tenantPlan).toBe('growth');
      expect(invite.inviteeEmail).toBe('chala@finfine.et');
    });
  });

  describe('2. Complete Tenant Onboarding Flow', () => {
    let inviteToken: string;
    let tenantId: string;
    const testSlug = `onboard-mart-${Date.now()}`;

    beforeAll(async () => {
      const adminLogin = await platformService.login({
        username: 'platform_admin',
        password: 'PlatformAdmin2026!',
      });

      const res = await platformService.createTenant(
        {
          name: 'Onboard Mart',
          slug: testSlug,
          plan: 'growth',
          ownerName: 'Tigist Alemu',
          ownerEmailOrPhone: '+251911998877',
        },
        adminLogin.admin.id,
      );
      inviteToken = res.inviteToken;
      tenantId = res.tenant.id;
    });

    it('successfully completes first-run wizard, provisions branch, terminal, and owner user', async () => {
      const result = await onboardingService.completeOnboarding({
        token: inviteToken,
        companyName: 'Onboard Mart PLC',
        tinNumber: '0098765432',
        vatSettings: { rate: 0.15, inclusive: false, vatNumber: 'VAT-9988-ET' },
        defaultLanguage: 'am',
        receiptHeader: 'Onboard Mart - Piazza Main Store',
        receiptFooter: 'እናመሰግናለን! እንደገና ይጎብኙን!',
        logoUrl: 'https://cdn.gebeyaos.et/logos/onboard-mart.png',
        branchCode: 'PIAZZA-01',
        branchName: 'Piazza Main Branch',
        branchCity: 'Addis Ababa',
        branchPhone: '+251 11 122 3344',
        ownerUsername: `owner_${Date.now()}`,
        ownerFullName: 'Tigist Alemu',
        ownerPhone: '+251 91 199 8877',
        ownerPassword: 'SecureOwnerPass2026!',
        ownerPin: '4321',
      });

      expect(result.accessToken).toBeDefined();
      expect(result.user.role).toBe('OWNER');
      expect(result.user.tenantId).toBe(tenantId);
      expect(result.user.branchCode).toBe('PIAZZA-01');
      expect(result.tenant.name).toBe('Onboard Mart PLC');
      expect(result.tenant.defaultLanguage).toBe('am');
      expect(result.checklist).toBeDefined();

      // Verify token is now marked as used
      await expect(onboardingService.verifyInvite(inviteToken)).rejects.toThrow(BadRequestException);
    });
  });

  describe('3. Dynamic Tenant Branding & Fiscal Settings', () => {
    it('retrieves and updates branding for a tenant', async () => {
      const kerodId = '01900000-0000-7000-8000-000000000001';

      const branding = await onboardingService.getBranding(kerodId);
      expect(branding.name).toBe('Kerod Supermarket');

      const updated = await onboardingService.updateBranding(kerodId, {
        receiptHeader: 'Kerod Supermarket - Bole Medhanialem Flagship',
        receiptFooter: 'Thank you for shopping at Kerod! / እናመሰግናለን!',
        defaultLanguage: 'am',
        logoUrl: 'https://cdn.gebeyaos.et/kerod-logo.png',
      });

      expect(updated.receiptHeader).toBe('Kerod Supermarket - Bole Medhanialem Flagship');
      expect(updated.logoUrl).toBe('https://cdn.gebeyaos.et/kerod-logo.png');
      expect(updated.defaultLanguage).toBe('am');
    });
  });

  describe('4. Branch Activation Codes Lifecycle', () => {
    const kerodId = '01900000-0000-7000-8000-000000000001';
    let generatedCode: string;

    beforeAll(async () => {
      await db.query(`UPDATE tenants SET max_branches = 50 WHERE id = $1`, [kerodId]);
    });

    it('generates an 8-character single-use activation code with expiry', async () => {
      const res = await activationService.generateCode(
        {
          branchName: 'Kerod Megenagna Branch',
          expiresInHours: 72,
        },
        '018e0000-0000-7000-8000-000000000041',
        kerodId,
      );

      expect(res.code).toBeDefined();
      expect(res.code.length).toBe(8);
      expect(res.branchName).toBe('Kerod Megenagna Branch');
      expect(res.expiresInHours).toBe(72);
      generatedCode = res.code;

      const list = await activationService.listCodes(kerodId);
      const found = list.find((c) => c.code === generatedCode);
      expect(found).toBeDefined();
      expect(found!.isUsed).toBe(false);
      expect(found!.isExpired).toBe(false);
    });

    it('branch LAN server registers and receives sync credentials using activation code', async () => {
      const dynamicCode = `MEG-${Date.now().toString().slice(-4)}`;
      const activationResult = await activationService.activateBranch({
        activationCode: generatedCode,
        branchCode: dynamicCode,
      });

      expect(activationResult.success).toBe(true);
      expect(activationResult.branchId).toBeDefined();
      expect(activationResult.branchCode).toBe(dynamicCode);
      expect(activationResult.branchName).toBe('Kerod Megenagna Branch');
      expect(activationResult.tenantId).toBe(kerodId);
      expect(activationResult.syncToken).toBeDefined();

      // Verify branch exists in database under this tenant
      const branchRow = await db.query(
        `SELECT id, name, code, tenant_id FROM branches WHERE id = $1`,
        [activationResult.branchId],
      );
      expect(branchRow.rows.length).toBe(1);
      expect(branchRow.rows[0].tenant_id).toBe(kerodId);
      expect(branchRow.rows[0].code).toBe(dynamicCode);

      // Attempting to reuse the same activation code must fail
      await expect(
        activationService.activateBranch({
          activationCode: generatedCode,
        }),
      ).rejects.toThrow(BadRequestException);
    });

    it('rejects invalid activation codes with NotFoundException', async () => {
      await expect(
        activationService.activateBranch({
          activationCode: 'INVALID9',
        }),
      ).rejects.toThrow(NotFoundException);
    });
  });
});
